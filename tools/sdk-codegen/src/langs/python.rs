use std::{
    collections::{HashMap, HashSet},
    fmt::Write,
};

use anyhow::Result;
use serde_json::Value;

use crate::model::{AdditionalProperties, Ir, Property, Shape};

pub fn emit(ir: &Ir) -> Result<String> {
    let identifiers = IdentifierMap::new(ir);
    let renderer = Renderer {
        ir,
        names: &identifiers.types,
    };
    let mut output = String::new();
    writeln!(output, "# Generated by ahp-codegen. DO NOT EDIT.")?;
    writeln!(
        output,
        "# Generated from AHP schema {}.",
        ir.schema_revision
    )?;
    writeln!(
        output,
        "# The source schema is authoritative if this output conflicts with it.\n"
    )?;
    output.push_str(PRELUDE);
    writeln!(
        output,
        "SCHEMA_REVISION: Final[str] = {}",
        python_string(&ir.schema_revision)?
    )?;
    writeln!(
        output,
        "PROTOCOL_VERSION: Final[str] = {}\n",
        python_string(&ir.protocol_version)?
    )?;

    for named in &ir.types {
        let name = identifiers.type_name(&named.name);
        writeln!(output, "# Source: {}", named.source)?;
        renderer.emit_declarations(&named.shape, name, true, &mut output)?;
        if renderer.model_properties(&named.shape).is_none()
            || matches!(named.shape, Shape::Ref { .. })
        {
            writeln!(
                output,
                "{name}: TypeAlias = {}",
                renderer.render(&named.shape, name)?
            )?;
        }
        output.push('\n');
    }

    let descriptors = ir
        .types
        .iter()
        .map(|named| {
            (
                named.name.clone(),
                serde_json::to_value(&named.shape).expect("shape serializes"),
            )
        })
        .collect::<serde_json::Map<_, _>>();
    let descriptors = serde_json::to_string(&descriptors)?;
    writeln!(
        output,
        "_SCHEMAS: dict[str, _SchemaNode] = json.loads({}, parse_float=Decimal)\n",
        python_string(&descriptors)?
    )?;
    output.push_str(RUNTIME);

    for (index, root) in ir.roots.iter().enumerate() {
        let function = &identifiers.roots[index];
        let type_name = identifiers.type_name(&root.name);
        writeln!(
            output,
            "def parse_{function}(input: str | JsonValue) -> ParseResult[{type_name}]:\n    return cast(ParseResult[{type_name}], _parse_root({}, input))\n",
            python_string(&root.name)?
        )?;
        writeln!(
            output,
            "def encode_{function}(value: {type_name}) -> str:\n    return _encode_json(cast(JsonValue, value))\n"
        )?;
        writeln!(
            output,
            "{function}_schema_revision: Final[str] = SCHEMA_REVISION\n"
        )?;
    }
    Ok(output)
}

struct IdentifierMap {
    types: HashMap<String, String>,
    roots: Vec<String>,
}

impl IdentifierMap {
    fn new(ir: &Ir) -> Self {
        let mut occupied = reserved_identifiers();
        let mut types = HashMap::new();
        for named in &ir.types {
            if !types.contains_key(&named.name) {
                let identifier = allocate_identifier(&named.name, "Type", &mut occupied);
                types.insert(named.name.clone(), identifier);
            }
        }

        let mut roots = Vec::with_capacity(ir.roots.len());
        for root in &ir.roots {
            let candidate = snake_case(&root.name);
            roots.push(allocate_root_identifier(&candidate, "root", &mut occupied));
        }
        Self { types, roots }
    }

    fn type_name(&self, source: &str) -> &str {
        self.types
            .get(source)
            .map(String::as_str)
            .unwrap_or("JsonValue")
    }
}

fn allocate_identifier(value: &str, fallback: &str, occupied: &mut HashSet<String>) -> String {
    let base = sanitize_identifier(value, fallback);
    let mut identifier = base.clone();
    let mut suffix = 2;
    while occupied.contains(&identifier) {
        identifier = format!("{base}_{suffix}");
        suffix += 1;
    }
    occupied.insert(identifier.clone());
    identifier
}

fn allocate_root_identifier(value: &str, fallback: &str, occupied: &mut HashSet<String>) -> String {
    let base = sanitize_identifier(value, fallback);
    let mut identifier = base.clone();
    let mut suffix = 2;
    while occupied.contains(&identifier)
        || occupied.contains(&format!("parse_{identifier}"))
        || occupied.contains(&format!("encode_{identifier}"))
        || occupied.contains(&format!("{identifier}_schema_revision"))
    {
        identifier = format!("{base}_{suffix}");
        suffix += 1;
    }
    occupied.insert(identifier.clone());
    occupied.insert(format!("parse_{identifier}"));
    occupied.insert(format!("encode_{identifier}"));
    occupied.insert(format!("{identifier}_schema_revision"));
    identifier
}

fn sanitize_identifier(value: &str, fallback: &str) -> String {
    let mut identifier = String::new();
    for character in value.chars() {
        if character.is_ascii_alphanumeric() || character == '_' {
            identifier.push(character);
        } else {
            identifier.push('_');
        }
    }
    if identifier.is_empty() {
        identifier.push_str(fallback);
    }
    if identifier.as_bytes()[0].is_ascii_digit() {
        identifier.insert(0, '_');
    }
    identifier
}

