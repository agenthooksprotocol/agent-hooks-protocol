struct Renderer<'a> {
    ir: &'a Ir,
    names: &'a HashMap<String, String>,
}

impl Renderer<'_> {
    fn emit_declarations(
        &self,
        shape: &Shape,
        hint: &str,
        public: bool,
        output: &mut String,
    ) -> Result<()> {
        // References are declared by their own stable-name entry. Following them here
        // causes direct and mutual recursive object graphs to recurse forever.
        if matches!(shape, Shape::Ref { .. }) {
            return Ok(());
        }
        if let Some(properties) = self.model_properties(shape) {
            for (index, property) in properties.iter().enumerate() {
                self.emit_declarations(
                    &property.shape,
                    &property_hint(hint, index, &property.wire_name),
                    false,
                    output,
                )?;
            }
            let name = self.model_name(hint, public);
            let fields = properties
                .iter()
                .enumerate()
                .map(|(index, property)| {
                    let annotation = self.render(
                        &property.shape,
                        &property_hint(hint, index, &property.wire_name),
                    )?;
                    let wrapper = if property.required {
                        "Required"
                    } else {
                        "NotRequired"
                    };
                    Ok(format!(
                        "{}: {wrapper}[{annotation}]",
                        python_string(&property.wire_name)?
                    ))
                })
                .collect::<Result<Vec<_>>>()?
                .join(", ");
            if self.allows_additional(shape) {
                let known_fields = self.known_fields_name(&name);
                writeln!(
                    output,
                    "{known_fields} = TypedDict({}, {{{fields}}}, total=False)",
                    python_string(&known_fields)?
                )?;
                writeln!(
                    output,
                    "{name}: TypeAlias = {known_fields} | JsonObject  # permits additional JSON fields"
                )?;
            } else {
                writeln!(
                    output,
                    "{name} = TypedDict({}, {{{fields}}}, total=False)",
                    python_string(&name)?
                )?;
            }
            return Ok(());
        }

        match shape {
            Shape::Array { items } => {
                self.emit_declarations(items, &format!("{hint}Item"), false, output)?
            }
            Shape::Union { variants, .. } | Shape::Intersection { variants } => {
                for (index, variant) in variants.iter().enumerate() {
                    self.emit_declarations(
                        variant,
                        &format!("{hint}Variant{index}"),
                        false,
                        output,
                    )?;
                }
            }
            Shape::Any
            | Shape::Never
            | Shape::Null
            | Shape::Boolean
            | Shape::Integer
            | Shape::Number
            | Shape::String
            | Shape::Literal { .. }
            | Shape::Enum { .. }
            | Shape::Ref { .. }
            | Shape::Object { .. } => {}
        }
        Ok(())
    }

    fn render(&self, shape: &Shape, hint: &str) -> Result<String> {
        Ok(match shape {
            Shape::Any => "JsonValue".into(),
            Shape::Never => "Never".into(),
            Shape::Null => "None".into(),
            Shape::Boolean => "bool".into(),
            Shape::Integer => "int | Decimal".into(),
            Shape::Number => "int | float | Decimal".into(),
            Shape::String => "str".into(),
            Shape::Literal { value } => render_literal(value)?,
            Shape::Enum {
                values,
                open_strings,
            } => render_enum(values, *open_strings)?,
            Shape::Array { items } => {
                format!("list[{}]", self.render(items, &format!("{hint}Item"))?)
            }
            Shape::Ref { name } => {
                python_string(self.names.get(name).map(String::as_str).unwrap_or(name))?
            }
            Shape::Object { .. } => self.model_name(hint, false),
            Shape::Union {
                variants,
                discriminator,
                ..
            } => {
                let mut rendered = variants
                    .iter()
                    .enumerate()
                    .map(|(index, variant)| self.render(variant, &format!("{hint}Variant{index}")))
                    .collect::<Result<Vec<_>>>()?;
                if discriminator.is_some() {
                    rendered.push("UnknownVariant".into());
                }
                render_union(rendered)
            }
            Shape::Intersection { variants } => {
                if self.model_properties(shape).is_some() {
                    self.model_name(hint, false)
                } else {
                    let rendered = variants
                        .iter()
                        .filter(|variant| !matches!(variant, Shape::Any))
                        .enumerate()
                        .map(|(index, variant)| {
                            self.render(variant, &format!("{hint}Variant{index}"))
                        })
                        .collect::<Result<Vec<_>>>()?;
                    if rendered.is_empty() {
                        "JsonValue".into()
                    } else {
                        let simplified = variants
                            .iter()
                            .cloned()
                            .reduce(intersect_shapes)
                            .expect("non-empty intersection");
                        if matches!(simplified, Shape::Intersection { .. }) {
                            // Python has no general intersection type. An unresolved
                            // intersection can still be satisfiable, so stay conservative.
                            "JsonValue".into()
                        } else {
                            self.render(&simplified, hint)?
                        }
                    }
                }
            }
        })
    }

    fn model_properties(&self, shape: &Shape) -> Option<Vec<Property>> {
        self.model_properties_inner(shape, &mut Vec::new())
    }

    fn model_name(&self, hint: &str, public: bool) -> String {
        if public {
            return hint.into();
        }
        let base = format!("_{hint}Model");
        let mut candidate = base.clone();
        let mut suffix = 2;
        while self.names.values().any(|stable| stable == &candidate) {
            candidate = format!("{base}_{suffix}");
            suffix += 1;
        }
        candidate
    }

    fn allows_additional(&self, shape: &Shape) -> bool {
        self.allows_additional_inner(shape, &mut Vec::new())
    }

    fn known_fields_name(&self, name: &str) -> String {
        let base = format!("_{name}KnownFields");
        let mut candidate = base.clone();
        let mut suffix = 2;
        while self.names.values().any(|stable| stable == &candidate) {
            candidate = format!("{base}_{suffix}");
            suffix += 1;
        }
        candidate
    }

    fn allows_additional_inner(&self, shape: &Shape, visiting: &mut Vec<String>) -> bool {
        match shape {
            Shape::Object { additional, .. } => matches!(additional, AdditionalProperties::Allowed),
            Shape::Intersection { variants } => variants
                .iter()
                .any(|variant| self.allows_additional_inner(variant, visiting)),
            Shape::Ref { name } => {
                if visiting.contains(name) {
                    return false;
                }
                let Some(named) = self.ir.types.iter().find(|item| item.name == *name) else {
                    return true;
                };
                visiting.push(name.clone());
                let result = self.allows_additional_inner(&named.shape, visiting);
                visiting.pop();
                result
            }
            _ => false,
        }
    }

    fn model_properties_inner(
        &self,
        shape: &Shape,
        visiting: &mut Vec<String>,
    ) -> Option<Vec<Property>> {
        match shape {
            Shape::Object {
                properties,
                additional,
                ..
            } => {
                match additional {
                    AdditionalProperties::Allowed | AdditionalProperties::Forbidden => {}
                }
                Some(properties.clone())
            }
            Shape::Intersection { variants } => {
                let mut merged = Vec::<Property>::new();
                for variant in variants {
                    if matches!(variant, Shape::Any) {
                        continue;
                    }
                    for property in self.model_properties_inner(variant, visiting)? {
                        if let Some(existing) = merged
                            .iter_mut()
                            .find(|item| item.wire_name == property.wire_name)
                        {
                            existing.required |= property.required;
                            existing.shape =
                                intersect_shapes(existing.shape.clone(), property.shape);
                        } else {
                            merged.push(property);
                        }
                    }
                }
                Some(merged)
            }
            Shape::Ref { name } => {
                if visiting.contains(name) {
                    return None;
                }
                let named = self.ir.types.iter().find(|item| item.name == *name)?;
                visiting.push(name.clone());
                let result = self.model_properties_inner(&named.shape, visiting);
                visiting.pop();
                result
            }
            Shape::Any
            | Shape::Never
            | Shape::Null
            | Shape::Boolean
            | Shape::Integer
            | Shape::Number
            | Shape::String
            | Shape::Literal { .. }
            | Shape::Enum { .. }
            | Shape::Array { .. }
            | Shape::Union { .. } => None,
        }
    }
}

fn intersect_shapes(left: Shape, right: Shape) -> Shape {
    if is_subshape(&left, &right) {
        return left;
    }
    if is_subshape(&right, &left) {
        return right;
    }
    Shape::Intersection {
        variants: vec![left, right],
    }
}

fn is_subshape(candidate: &Shape, broad: &Shape) -> bool {
    if matches!(broad, Shape::Any)
        || serde_json::to_value(candidate).expect("shape serializes")
            == serde_json::to_value(broad).expect("shape serializes")
    {
        return true;
    }
    match (candidate, broad) {
        (Shape::Integer, Shape::Number) => true,
        (Shape::Literal { value }, Shape::String) => value.is_string(),
        (Shape::Literal { value }, Shape::Boolean) => value.is_boolean(),
        (Shape::Literal { value }, Shape::Null) => value.is_null(),
        (Shape::Literal { value }, Shape::Integer) => {
            value.as_i64().is_some() || value.as_u64().is_some()
        }
        (Shape::Literal { value }, Shape::Number) => value.is_number(),
        (Shape::Enum { values, .. }, Shape::String) => values.iter().all(Value::is_string),
        (Shape::Enum { values, .. }, Shape::Integer) => values
            .iter()
            .all(|value| value.as_i64().is_some() || value.as_u64().is_some()),
        (Shape::Enum { values, .. }, Shape::Number) => values.iter().all(Value::is_number),
        _ => false,
    }
}

fn render_union(mut variants: Vec<String>) -> String {
    variants.dedup();
    match variants.len() {
        0 => "Never".into(),
        1 => variants.pop().expect("one variant"),
        _ => format!("Union[{}]", variants.join(", ")),
    }
}

fn render_enum(values: &[Value], open_strings: bool) -> Result<String> {
    if open_strings {
        return Ok("OpenString".into());
    }
    let mut variants = Vec::new();
    for value in values {
        let annotation = match value {
            Value::Number(number) if number.is_f64() => "float".into(),
            Value::Array(_) | Value::Object(_) => "JsonValue".into(),
            _ => format!("Literal[{}]", python_value(value)?),
        };
        if !variants.contains(&annotation) {
            variants.push(annotation);
        }
    }
    Ok(render_union(variants))
}

fn render_literal(value: &Value) -> Result<String> {
    match value {
        Value::Number(number) if number.is_f64() => Ok("float".into()),
        Value::Null | Value::Bool(_) | Value::Number(_) | Value::String(_) => {
            Ok(format!("Literal[{}]", python_value(value)?))
        }
        Value::Array(_) | Value::Object(_) => Ok("JsonValue".into()),
    }
}

fn python_value(value: &Value) -> Result<String> {
    Ok(match value {
        Value::Null => "None".into(),
        Value::Bool(true) => "True".into(),
        Value::Bool(false) => "False".into(),
        Value::Number(number) => number.to_string(),
        Value::String(value) => python_string(value)?,
        Value::Array(_) | Value::Object(_) => "JsonValue".into(),
    })
}

fn property_hint(parent: &str, index: usize, wire_name: &str) -> String {
    format!("{parent}Field{index}{}", pascal_fragment(wire_name))
}

fn python_string(value: &str) -> Result<String> {
    Ok(serde_json::to_string(value)?)
}

fn snake_case(value: &str) -> String {
    let chars = value.chars().collect::<Vec<_>>();
    let mut result = String::new();
    for (index, current) in chars.iter().copied().enumerate() {
        let previous = index
            .checked_sub(1)
            .and_then(|item| chars.get(item))
            .copied();
        let next = chars.get(index + 1).copied();
        if current.is_uppercase()
            && !result.is_empty()
            && (previous.is_some_and(|item| item.is_lowercase() || item.is_ascii_digit())
                || (previous.is_some_and(char::is_uppercase)
                    && next.is_some_and(char::is_lowercase)))
        {
            result.push('_');
        }
        for lowered in current.to_lowercase() {
            result.push(lowered);
        }
    }
    result
}

fn pascal_fragment(value: &str) -> String {
    let mut result = String::new();
    let mut uppercase_next = true;
    for character in value.chars() {
        if character.is_ascii_alphanumeric() {
            if uppercase_next {
                result.extend(character.to_uppercase());
                uppercase_next = false;
            } else {
                result.push(character);
            }
        } else {
            uppercase_next = true;
        }
    }
    if result.is_empty() {
        "Field".into()
    } else {
        result
    }
}

